function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function stripMarkdown(value) {
  return value
    .replace(/!\[([^\]]*)\]\([^)]+\)/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/[`*_~]/g, '')
    .replace(/\\([\\`*_[\]{}()#+\-.!|])/g, '$1')
    .trim();
}

function slugify(value) {
  return stripMarkdown(value)
    .normalize('NFKD')
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-');
}

function rewriteUrl(rawUrl) {
  const value = rawUrl.trim();
  if (/^\.\.\/images\//.test(value)) {
    return `/assets/guides/${path.posix.basename(value)}`;
  }
  const markdownMatch = value.match(/^(?:\.\/)?([^/#]+)\.md(#[^\s]+)?$/);
  if (markdownMatch) return `/guides/${markdownMatch[1]}${markdownMatch[2] || ''}`;
  if (/^(?:https?:\/\/|\/|#)/.test(value)) return value;
  return value.replace(/^\.\//, '');
}

function renderInline(value) {
  const tokens = [];
  const hold = (html) => {
    const marker = `\uE000${tokens.length}\uE001`;
    tokens.push(html);
    return marker;
  };
  let output = value.replace(/`([^`]+)`/g, (_, code) => hold(`<code>${escapeHtml(code)}</code>`));
  output = output.replace(
    /\[([^\]]+)\]\(([^)\s]+)(?:\s+["']([^"']*)["'])?\)/g,
    (_, label, rawUrl, title) => {
      const href = rewriteUrl(rawUrl);
      const external = /^https?:\/\//.test(href);
      const titleAttribute = title ? ` title="${escapeHtml(title)}"` : '';
      const externalAttributes = external ? ' target="_blank" rel="noopener noreferrer"' : '';
      return hold(
        `<a href="${escapeHtml(href)}"${titleAttribute}${externalAttributes}>${renderInline(label)}</a>`
      );
    }
  );
  output = output.replace(/\\([\\`*_[\]{}()#+\-.!|])/g, '$1');
  output = escapeHtml(output);
  output = output.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  output = output.replace(/(^|[^*])\*([^*\n]+)\*(?!\*)/g, '$1<em>$2</em>');
  output = output.replace(/~~([^~]+)~~/g, '<del>$1</del>');
  tokens.forEach((html, index) => {
    output = output.replace(`\uE000${index}\uE001`, html);
  });
  return output;
}

function splitTableRow(line) {
  return line
    .trim()
    .replace(/^\|/, '')
    .replace(/\|$/, '')
    .split(/(?<!\\)\|/)
    .map((cell) => cell.trim().replace(/\\\|/g, '|'));
}

function isTableSeparator(line) {
  const cells = splitTableRow(line);
  return cells.length > 0 && cells.every((cell) => /^:?-+:?$/.test(cell));
}

function isBlockStart(lines, index) {
  const line = lines[index] || '';
  const next = lines[index + 1] || '';
  return (
    /^#{1,6}\s+/.test(line) ||
    /^```/.test(line) ||
    /^\s*(?:[-*+] |\d+\. )/.test(line) ||
    /^---+$/.test(line.trim()) ||
    /^!\[[^\]]*\]\([^)]+\)\s*$/.test(line.trim()) ||
    (line.includes('|') && isTableSeparator(next))
  );
}

function indentationWidth(value) {
  let width = 0;
  for (const character of value) {
    if (character === '\t') width += 4 - (width % 4);
    else width += 1;
  }
  return width;
}

function parseListMarker(line) {
  const match = line.match(/^([ \t]*)([-*+]|(\d+)\.)[ \t]+(.+)$/);
  if (!match) return null;
  return {
    indent: indentationWidth(match[1]),
    ordered: Boolean(match[3]),
    start: match[3] ? Number(match[3]) : null,
    content: match[4],
  };
}

function renderList(lines, startIndex) {
  const first = parseListMarker(lines[startIndex] || '');
  if (!first) throw new Error('List rendering must begin on a list item.');

  const baseIndent = first.indent;
  const ordered = first.ordered;
  const items = [];
  let index = startIndex;

  while (index < lines.length) {
    const marker = parseListMarker(lines[index]);
    if (!marker || marker.indent !== baseIndent || marker.ordered !== ordered) break;

    const blocks = [];
    const continuation = [];
    let endList = false;
    index += 1;

    const flushContinuation = () => {
      if (!continuation.length) return;
      blocks.push(`<p>${renderInline(continuation.join(' '))}</p>`);
      continuation.length = 0;
    };

    while (index < lines.length) {
      const line = lines[index];
      if (!line.trim()) {
        let nextIndex = index + 1;
        while (nextIndex < lines.length && !lines[nextIndex].trim()) nextIndex += 1;
        if (nextIndex >= lines.length) {
          index = nextIndex;
          endList = true;
          break;
        }

        const nextMarker = parseListMarker(lines[nextIndex]);
        if (nextMarker && nextMarker.indent === baseIndent && nextMarker.ordered === ordered) {
          index = nextIndex;
          break;
        }

        const nextIndent = indentationWidth((lines[nextIndex].match(/^[ \t]*/) || [''])[0]);
        if ((nextMarker && nextMarker.indent > baseIndent) || nextIndent > baseIndent) {
          flushContinuation();
          index = nextIndex;
          continue;
        }

        index = nextIndex;
        endList = true;
        break;
      }

      const nestedMarker = parseListMarker(line);
      if (nestedMarker) {
        if (nestedMarker.indent === baseIndent) {
          if (nestedMarker.ordered !== ordered) endList = true;
          break;
        }
        if (nestedMarker.indent < baseIndent) {
          endList = true;
          break;
        }

        flushContinuation();
        const nested = renderList(lines, index);
        blocks.push(nested.html);
        index = nested.nextIndex;
        continue;
      }

      const lineIndent = indentationWidth((line.match(/^[ \t]*/) || [''])[0]);
      if (lineIndent > baseIndent) {
        continuation.push(line.trim());
        index += 1;
        continue;
      }

      endList = true;
      break;
    }

    flushContinuation();
    items.push(`<li>${renderInline(marker.content)}${blocks.join('')}</li>`);
    if (endList) break;
  }

  const tag = ordered ? 'ol' : 'ul';
  const start = ordered && first.start !== 1 ? ` start="${first.start}"` : '';
  return { html: `<${tag}${start}>${items.join('')}</${tag}>`, nextIndex: index };
}

function svgDimensions(fileName) {
  const sourcePath = path.join(imageSourceRoot, fileName);
  if (!fs.existsSync(sourcePath) || path.extname(fileName).toLowerCase() !== '.svg') return '';
  const svg = fs.readFileSync(sourcePath, 'utf8');
  const viewBox = svg.match(/viewBox=["'](?:[-\d.]+\s+){2}([\d.]+)\s+([\d.]+)["']/i);
  if (!viewBox) return '';
  return ` width="${Math.round(Number(viewBox[1]))}" height="${Math.round(Number(viewBox[2]))}"`;
}

function renderMarkdown(markdown) {
  const lines = markdown
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .split('\n');
  const headings = [];
  const usedIds = new Map();
  const referencedImages = new Set();
  const output = [];
  let title = '';
  let index = 0;

  const uniqueId = (heading) => {
    const base = slugify(heading) || 'section';
    const count = usedIds.get(base) || 0;
    usedIds.set(base, count + 1);
    return count ? `${base}-${count + 1}` : base;
  };

  while (index < lines.length) {
    const line = lines[index];
    if (!line.trim()) {
      index += 1;
      continue;
    }

    const fence = line.match(/^```\s*([\w-]+)?\s*$/);
    if (fence) {
      const code = [];
      index += 1;
      while (index < lines.length && !/^```\s*$/.test(lines[index])) {
        code.push(lines[index]);
        index += 1;
      }
      if (index < lines.length) index += 1;
      const language = fence[1] ? ` class="language-${escapeHtml(fence[1])}"` : '';
      output.push(`<pre><code${language}>${escapeHtml(code.join('\n'))}</code></pre>`);
      continue;
    }

    const heading = line.match(/^(#{1,6})\s+(.+)$/);
    if (heading) {
      let level = heading[1].length;
      const headingText = stripMarkdown(heading[2]);
      if (level === 1 && !title) {
        title = headingText;
        index += 1;
        continue;
      }
      if (level === 1) level = 2;
      const id = uniqueId(headingText);
      if (level === 2) headings.push({ id, text: headingText });
      output.push(`<h${level} id="${id}">${renderInline(heading[2])}</h${level}>`);
      index += 1;
      continue;
    }

    const image = line.trim().match(/^!\[([^\]]*)\]\(([^)\s]+)(?:\s+["']([^"']*)["'])?\)$/);
    if (image) {
      const imageUrl = rewriteUrl(image[2]);
      const fileName = path.posix.basename(imageUrl);
      referencedImages.add(fileName);
      output.push(
        `<figure class="guide-figure"><img src="${escapeHtml(imageUrl)}" alt="${escapeHtml(
          image[1]
        )}"${svgDimensions(fileName)} loading="lazy" decoding="async" /><figcaption>${renderInline(
          image[1]
        )}</figcaption></figure>`
      );
      index += 1;
      continue;
    }

    if (line.includes('|') && isTableSeparator(lines[index + 1] || '')) {
      const headers = splitTableRow(line);
      const separators = splitTableRow(lines[index + 1]);
      const alignments = separators.map((cell) =>
        cell.startsWith(':') && cell.endsWith(':')
          ? 'center'
          : cell.endsWith(':')
            ? 'right'
            : cell.startsWith(':')
              ? 'left'
              : ''
      );
      index += 2;
      const rows = [];
      while (index < lines.length && lines[index].trim() && lines[index].includes('|')) {
        rows.push(splitTableRow(lines[index]));
        index += 1;
      }
      const cellStyle = (cellIndex) =>
        alignments[cellIndex] ? ` style="text-align: ${alignments[cellIndex]}"` : '';
      output.push(
        '<div class="guide-table-wrap" role="region" aria-label="Scrollable data table" tabindex="0"><table><thead><tr>' +
          headers
            .map(
              (cell, cellIndex) =>
                `<th${cellStyle(cellIndex)} scope="col">${renderInline(cell)}</th>`
            )
            .join('') +
          '</tr></thead><tbody>' +
          rows
            .map(
              (row) =>
                '<tr>' +
                headers
                  .map(
                    (_, cellIndex) =>
                      `<td${cellStyle(cellIndex)}>${renderInline(row[cellIndex] || '')}</td>`
                  )
                  .join('') +
                '</tr>'
            )
            .join('') +
          '</tbody></table></div>'
      );
      continue;
    }

    if (parseListMarker(line)) {
      const renderedList = renderList(lines, index);
      output.push(renderedList.html);
      index = renderedList.nextIndex;
      continue;
    }

    if (/^---+$/.test(line.trim())) {
      output.push('<hr />');
      index += 1;
      continue;
    }

    const paragraph = [];
    while (index < lines.length && lines[index].trim() && !isBlockStart(lines, index)) {
      paragraph.push(lines[index].trim());
      index += 1;
    }
    if (paragraph.length) {
      output.push(`<p>${renderInline(paragraph.join(' '))}</p>`);
      continue;
    }

    // This prevents a malformed source line from stalling generation.
    output.push(`<p>${renderInline(line.trim())}</p>`);
    index += 1;
  }

  if (!title) throw new Error('Guide source is missing its level-one heading.');
  return { title, html: output.join('\n'), headings, referencedImages };
}

function wordCount(markdown) {
  return (stripMarkdown(markdown).match(/[\p{L}\p{N}]+/gu) || []).length;
}

